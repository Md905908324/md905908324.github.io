function highlightConnections() {
  const application = applications.find(item => item.id === activeApplication);
  const relatedApplications = new Set(applications.filter(item => activeSkill ? item.inputs.includes(activeSkill) : item.id === activeApplication).map(item => item.id));
  const inputSkills = new Set(application ? application.inputs : activeSkill ? [activeSkill] : selectedBranch ? skillData.network[selectedBranch] : []);
  for (const node of skillNodes) node.classList.toggle('is-highlighted', inputSkills.has(node.dataset.node));
  for (const node of applicationNodes) {
    const item = applications.find(item => item.id === node.dataset.application);
    node.classList.toggle('is-highlighted', relatedApplications.has(item.id) || (!activeApplication && !activeSkill && selectedBranch && item.inputs.some(id => inputSkills.has(id))));
  }
  for (const edge of connections) {
    let active = false;
    if (edge.kind === 'domain') active = inputSkills.has(edge.skill);
    else if (edge.kind === 'application') active = activeApplication ? edge.application === activeApplication : inputSkills.has(edge.skill);
    else active = activeApplication ? edge.apps.includes(activeApplication) : edge.apps.every(id => relatedApplications.has(id));
    edge.path.classList.toggle('is-active', active);
  }
}

function drawSkillConnections() {
  const bounds = skillNetwork.getBoundingClientRect();
  connectionLayer.setAttribute('viewBox', `0 0 ${bounds.width} ${bounds.height}`);
  connectionLayer.replaceChildren(); connections = [];
  const stacked = getComputedStyle(skillNetwork).gridTemplateColumns.split(' ').length === 1;
  function point(element) {
    const r = element.getBoundingClientRect();
    return {x: r.left + r.width / 2 - bounds.left, y: r.top + r.height / 2 - bounds.top};
  }
  function connect(from, to, meta) {
    const start = point(from), end = point(to);
    const mx = (start.x + end.x) / 2, my = (start.y + end.y) / 2;
    const path = document.createElementNS('http://www.w3.org/2000/svg', 'path');
    path.setAttribute('d', meta.kind === 'mesh'
      ? `M ${start.x} ${start.y} Q ${mx + 24} ${my}, ${end.x} ${end.y}`
      : stacked ? `M ${start.x} ${start.y} C ${start.x} ${my}, ${end.x} ${my}, ${end.x} ${end.y}`
      : `M ${start.x} ${start.y} C ${mx} ${start.y}, ${mx} ${end.y}, ${end.x} ${end.y}`);
    path.classList.add('skill-connection', meta.kind + '-connection');
    connectionLayer.append(path); connections.push({...meta, path});
  }
  for (const node of skillNodes) {
    const hub = skillHubs.find(hub => hub.dataset.hub === node.dataset.domain);
    connect(hub, node, {kind: 'domain', skill: node.dataset.node});
  }
  for (const app of applications) {
    const target = applicationNodes.find(node => node.dataset.application === app.id);
    for (const id of app.inputs) {
      const source = skillNodes.find(node => node.dataset.node === id);
      if (source) connect(source, target, {kind: 'application', skill: id, application: app.id});
    }
  }
  for (let i = 0; i < applications.length; i++) {
    for (let j = i + 1; j < applications.length; j++) {
      const shared = applications[i].inputs.filter(id => applications[j].inputs.includes(id));
      if (shared.length < 2) continue;
      connect(applicationNodes[i], applicationNodes[j], {kind: 'mesh', apps: [applications[i].id, applications[j].id]});
    }
  }
  highlightConnections();
}
for (const node of [...skillNodes, ...applicationNodes]) {
  function activate() {
    activeApplication = node.dataset.application || null;
    activeSkill = node.dataset.node || null;
    highlightConnections();
  }
  function clear() { activeSkill = null; activeApplication = null; highlightConnections(); }
  node.addEventListener('pointerenter', activate); node.addEventListener('pointerleave', clear);
  node.addEventListener('focus', activate); node.addEventListener('blur', clear);
}
for (const hub of skillHubs) {
  hub.addEventListener('click', () => {
    selectedBranch = selectedBranch === hub.dataset.hub ? null : hub.dataset.hub;
    activeSkill = null; activeApplication = null;
    skillHubs.forEach(item => item.setAttribute('aria-pressed', String(item.dataset.hub === selectedBranch)));
    document.getElementById('network-status').textContent = selectedBranch ? `${selectedBranch === 'tech' ? 'Tech' : 'Finance and business'} connections highlighted.` : 'All skills shown without highlighting.';
    highlightConnections();
  });
}
