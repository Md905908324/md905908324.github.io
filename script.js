function revealPageTarget(hash) {
  const target = document.querySelector(hash);
  if (!target) return;
  if (hash.startsWith('#project-')) {
    projectSearch.value = '';
    projectSearch.dispatchEvent(new Event('input'));
  }
  if (hash.startsWith('#course-')) filterCourses('all');
  let ancestor = target.matches('details') ? target : target.closest('details');
  while (ancestor) {
    ancestor.open = true;
    ancestor = ancestor.parentElement.closest('details');
  }
  requestAnimationFrame(() => {
    target.scrollIntoView({block: 'start', behavior: matchMedia('(prefers-reduced-motion: reduce)').matches ? 'auto' : 'smooth'});
    target.setAttribute('tabindex', '-1');
    target.focus({preventScroll: true});
  });
}

function renderSkillEvidence() {
  const evidence = currentSkill.evidence.map(id => skillData.evidence[id]);
  for (const button of tabButtons) {
    const group = button.dataset.evidenceGroup;
    const count = evidence.filter(item => item.category === group).length;
    button.textContent = `${groupLabels[group]} (${count})`;
    button.disabled = count === 0;
    button.setAttribute('aria-selected', String(group === currentEvidenceGroup));
    button.tabIndex = group === currentEvidenceGroup ? 0 : -1;
  }
  evidenceContainer.setAttribute('aria-labelledby', 'evidence-tab-' + currentEvidenceGroup);
  evidenceContainer.replaceChildren();
  for (const entry of evidence.filter(item => item.category === currentEvidenceGroup)) {
    const item = document.createElement('article');
    item.className = 'evidence-item';
    const type = document.createElement('p');
    type.className = 'eyebrow';
    type.textContent = entry.status ? `${entry.type} · ${entry.status}` : entry.type;
    const heading = document.createElement('h3');
    if (entry.href) {
      const link = document.createElement('a');
      link.href = entry.href;
      link.textContent = entry.title;
      if (!entry.href.startsWith('#')) { link.target = '_blank'; link.rel = 'noopener noreferrer'; }
      link.addEventListener('click', event => {
        dialog.close();
        if (entry.href.startsWith('#')) { event.preventDefault(); revealPageTarget(entry.href); }
      });
      heading.append(link);
    } else heading.textContent = entry.title;
    const description = document.createElement('p');
    description.textContent = entry.description;
    item.append(type, heading, description);
    evidenceContainer.append(item);
  }
}

