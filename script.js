const dialog = document.getElementById('skill-dialog');
const title = document.getElementById('skill-title');
const evidenceContainer = document.getElementById('skill-evidence');

// Native dialog provides focus trapping, Escape support, and focus restoration.
document.addEventListener('click', event => {
  const trigger = event.target.closest('[data-skill]');
  if (!trigger) return;
  const skill = skillData.skills[trigger.dataset.skill];
  if (!skill) return;
  title.textContent = skill.name;
  evidenceContainer.replaceChildren();
  for (const evidenceId of skill.evidence) {
    const evidence = skillData.evidence[evidenceId];
    const item = document.createElement('article');
    item.className = 'evidence-item';
    const type = document.createElement('p');
    type.className = 'eyebrow';
    type.textContent = evidence.type;
    const heading = document.createElement('h3');
    if (evidence.href) {
      const link = document.createElement('a');
      link.href = evidence.href;
      if (!evidence.href.startsWith('#')) {
        link.target = '_blank';
        link.rel = 'noopener noreferrer';
      }
      link.textContent = evidence.title;
      link.addEventListener('click', () => {
        dialog.close();
        const target = evidence.href.startsWith('#') ? document.querySelector(evidence.href) : null;
        if (!target) return;
        const details = target.matches('details') ? target : target.querySelector('details');
        if (details) details.open = true;
        requestAnimationFrame(() => {
          target.scrollIntoView({block: 'start', behavior: matchMedia('(prefers-reduced-motion: reduce)').matches ? 'auto' : 'smooth'});
          target.setAttribute('tabindex', '-1');
          target.focus({preventScroll: true});
        });
      });
      heading.append(link);
    } else heading.textContent = evidence.title;
    const description = document.createElement('p');
    description.textContent = evidence.description;
    item.append(type, heading, description);
    evidenceContainer.append(item);
  }
  dialog.showModal();
});
dialog.querySelector('.dialog-close').addEventListener('click', () => dialog.close());
dialog.addEventListener('click', event => {
  const rect = dialog.getBoundingClientRect();
  if (event.clientX < rect.left || event.clientX > rect.right || event.clientY < rect.top || event.clientY > rect.bottom) dialog.close();
});

